/* Generate engine/text-metrics.js: approximate font metric tables for the fixture fonts, measured
 * in Chromium (canvas measureText at 1000 px → units per em/1000) so that the Node text measurer
 * reproduces the browser's advances (incl. kerning pairs) closely.
 *
 *   node engine/conformance/tools/gen-font-metrics.js
 */
const path = require('path');
const fs = require('fs');
const { chromium } = require('playwright');

const FONTS = [
  { family: 'Inter', weights: [400, 500, 600, 700], upm: 2048, ascender: 1984, descender: -494, lineGap: 0 },
  { family: 'DejaVu Sans', weights: [400, 700], upm: 2048, ascender: 1901, descender: -483, lineGap: 0 }
];
const CHARS = (() => {
  let s = '';
  for (let c = 32; c <= 126; c++) s += String.fromCharCode(c);
  s += 'àâäçéèêëîïôöùûüÿœæÀÂÄÇÉÈÊËÎÏÔÖÙÛÜŸŒÆ€’‘“”«»–—…·°•×';
  return s;
})();
const KERN_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.,:;\'"-/()!?éèàç';

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent('<!doctype html><html><body></body></html>');
  const data = await page.evaluate(({ FONTS, CHARS, KERN_CHARS }) => {
    const ctx = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const f of FONTS) {
      for (const w of f.weights) {
        ctx.font = `${w} 1000px '${f.family}'`;
        const adv = {};
        for (const ch of CHARS) adv[ch] = Math.round(ctx.measureText(ch).width * 100) / 100;
        const kern = {};
        for (const a of KERN_CHARS) for (const b of KERN_CHARS) {
          const k = ctx.measureText(a + b).width - adv[a] - adv[b];
          if (Math.abs(k) > 0.5) kern[a + b] = Math.round(k * 10) / 10;
        }
        out[f.family + '/' + w] = { adv, kern };
      }
    }
    return out;
  }, { FONTS, CHARS, KERN_CHARS });
  await browser.close();

  let js = '/* DualEngine — text-metrics.js (GENERATED by conformance/tools/gen-font-metrics.js — do not edit)\n';
  js += ' * Approximate metric tables for the fixture fonts, measured in Chromium: advances and kerning\n';
  js += ' * pairs in 1/1000 em, vertical metrics from hhea (units per em). */\n';
  js += '(function (global, factory) {\n  \'use strict\';\n  var api = factory();\n';
  js += '  if (typeof module !== \'undefined\' && module.exports) module.exports = api;\n';
  js += '  else (global.DualEngine = global.DualEngine || {}).textMetrics = api;\n';
  js += '})(typeof window !== \'undefined\' ? window : globalThis, function () {\n  \'use strict\';\n  var fonts = {};\n';
  for (const f of FONTS) {
    js += `  fonts[${JSON.stringify(f.family)}] = { upm: ${f.upm}, ascender: ${f.ascender}, descender: ${f.descender}, lineGap: ${f.lineGap}, weights: {} };\n`;
    for (const w of f.weights) {
      const d = data[f.family + '/' + w];
      js += `  fonts[${JSON.stringify(f.family)}].weights[${w}] = { adv: ${JSON.stringify(d.adv)}, kern: ${JSON.stringify(d.kern)} };\n`;
    }
  }
  js += '  return { fonts: fonts, generatedBy: \'Chromium canvas measureText @1000px\' };\n});\n';
  const outPath = path.join(__dirname, '..', '..', 'text-metrics.js');
  // ASCII only (\u escapes): the classic script decodes the same whatever charset it is served with
  fs.writeFileSync(outPath, js.replace(/[\u0080-\uffff]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0')));
  console.log('wrote', outPath, (js.length / 1024).toFixed(1) + ' KB');
})();
